"""
Universal Skill.md Installer and Exporter for SkillForge.
Installs generated skills directly into Antigravity, Claude, Grok, or packages as a ZIP bundle.
"""

from __future__ import annotations
import zipfile
import io
from pathlib import Path
from typing import Optional, Dict, Any
from datetime import datetime


class SkillInstaller:
    """Install skills to local agent folders or package as ZIP."""

    @staticmethod
    def install_claude(skill_name: str, skill_md: str, base: Optional[Path] = None) -> Path:
        root = base or Path.home() / ".claude" / "skills"
        dest = root / skill_name
        dest.mkdir(parents=True, exist_ok=True)
        path = dest / "SKILL.md"
        path.write_text(skill_md, encoding="utf-8")
        return path

    @staticmethod
    def install_antigravity(skill_name: str, skill_md: str, base: Optional[Path] = None) -> Path:
        root = base or Path.home() / ".gemini" / "config" / "skills"
        dest = root / skill_name
        dest.mkdir(parents=True, exist_ok=True)
        path = dest / "SKILL.md"
        path.write_text(skill_md, encoding="utf-8")
        return path

    @staticmethod
    def install_workspace(skill_name: str, skill_md: str, workspace: Path) -> Dict[str, Path]:
        """Mirror into project .claude/skills and .grok/skills."""
        results = {}
        for rel in [".claude/skills", ".grok/skills"]:
            dest = workspace / rel / skill_name
            dest.mkdir(parents=True, exist_ok=True)
            path = dest / "SKILL.md"
            path.write_text(skill_md, encoding="utf-8")
            results[rel] = path
        return results

    @staticmethod
    def export_zip(skill_name: str, skill_md: str) -> bytes:
        buf = io.BytesIO()
        readme = f"""# {skill_name}

Universal Agent Skill package compatible with:
- Claude Code & Claude Desktop (`~/.claude/skills/{skill_name}/`)
- Free Claude Code / FCC (https://github.com/Alishahryar1/free-claude-code)
  Use the same Claude (or Antigravity / other harness) skill folders — FCC routes the agent.
- Google Antigravity (`~/.gemini/config/skills/{skill_name}/`)
- xAI Grok (`.grok/skills/{skill_name}/`)
- OpenAI ChatGPT / Custom GPTs (instructions body)
- Google Gemini System Instructions

Generated by Titus SkillForge.
"""
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
            zf.writestr(f"{skill_name}/SKILL.md", skill_md)
            zf.writestr(f"{skill_name}/README.md", readme)
        return buf.getvalue()
